import { chromium } from 'playwright';
import { mkdir,writeFile } from 'node:fs/promises';
const base=process.env.VIENNANOW_TEST_URL||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:390,height:780},hasTouch:true,isMobile:true,reducedMotion:'reduce'});
const page=await ctx.newPage(),checks=[],issues=[];
const check=(name,ok,detail='')=>{checks.push({name,ok:!!ok,detail});if(!ok)issues.push(name+': '+detail)};
await mkdir('artifacts/course-qa',{recursive:true});
page.on('pageerror',e=>issues.push('JavaScript '+e.message));
await page.route('**/*',route=>route.request().url().startsWith(base+'/')?route.continue():route.abort());
try{
 await page.goto(base+'/index.html',{waitUntil:'domcontentloaded'});
 await page.locator('#bottom button.tab[data-value="itinerary"]').click();
 await page.locator('button[data-act="vn-course-detail"]').first().click();
 const detail=page.locator('#main .vn-course-swipe');
 await detail.waitFor();
 const first=await page.locator('#main .vn36-detail .kicker').first().innerText();
 check('Route details open',first.includes('B01'),first);
 check('Pre-trip notice removed',!(await detail.innerText()).includes('여행 전 확인'));
 check('Google start/finish link replaced',await detail.locator('a[href*="google.com/maps/dir"]').count()===0);
 check('Nearby route button appears',await detail.locator('button[data-act="vn-course-near-map"]').count()===1);
 await detail.locator('button[data-act="vn-course-slide"][data-value="1"]').click();
 const second=await page.locator('#main .vn36-detail .kicker').first().innerText();
 check('Next route arrow works',second.includes('B02'),second);
 await page.locator('#main .vn36-detail button[data-act="vn-course-slide"][data-value="-1"]').click();
 check('Previous route arrow works',(await page.locator('#main .vn36-detail .kicker').first().innerText()).includes('B01'));
 const swipe=async(left)=>{
  const target=page.locator('#main .vn-course-swipe .pro-plan');
  const startX=left?300:75,endX=left?90:295;
  await target.dispatchEvent('touchstart',{touches:[{identifier:1,clientX:startX,clientY:260}]});
  await target.dispatchEvent('touchmove',{touches:[{identifier:1,clientX:(startX+endX)/2,clientY:260}]});
  await target.dispatchEvent('touchmove',{touches:[{identifier:1,clientX:endX,clientY:260}]});
  await target.dispatchEvent('touchend',{changedTouches:[{identifier:1,clientX:endX,clientY:260}]});
  await page.waitForTimeout(80);
 };
 await swipe(true);
 check('Swipe left navigates to next route',(await page.locator('#main .vn36-detail .kicker').first().innerText()).includes('B02'));
 await swipe(false);
 check('Swipe right navigates to previous route',(await page.locator('#main .vn36-detail .kicker').first().innerText()).includes('B01'));
 await page.locator('#main .vn36-detail button[data-act="vn-course-slide"][data-value="1"]').click();
 const mapButton=page.locator('#main button[data-act="vn-course-near-map"]');
 check('Selected route map button targets B02',await mapButton.getAttribute('data-id')==='B02');
 await mapButton.click();
 check('Nearby map tab activated',await page.locator('#bottom button.tab.active[data-value="map"]').count()===1);
 check('Nearby plan category selected',await page.locator('#main button[data-act="section-near"].active[data-value="plan"]').count()===1);
 check('Selected route preserved in map dropdown',await page.locator('#near-plan-choice').inputValue()==='B02');
 check('Route detail replaced by map',await page.locator('#main .vn-course-swipe').count()===0);
 await page.screenshot({path:'artifacts/course-qa/nearby-selected-route.png',animations:'disabled'});
}catch(e){issues.push('Flow '+String(e.stack||e).slice(0,1400))}
await writeFile('artifacts/course-qa/report.json',JSON.stringify({checks,issues},null,2));
await browser.close();
console.log('Route detail QA '+checks.filter(x=>x.ok).length+'/'+checks.length+' passing; '+issues.length+' issues');
for(const x of issues)console.error('FAIL '+x);
if(issues.length)process.exitCode=1;
