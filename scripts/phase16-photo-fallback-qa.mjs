import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
const base=process.env.VIENNANOW_TEST_URL||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:780},reducedMotion:'reduce'});
const page=await context.newPage(),checks=[],issues=[];
const check=(name,ok,detail='')=>{checks.push({name,ok:!!ok,detail});if(!ok)issues.push(name+': '+detail)};
await mkdir('artifacts/phase16',{recursive:true});
page.on('pageerror',e=>issues.push('JS: '+e.message));
await page.route('**/*',route=>route.request().url().startsWith(base+'/')?route.continue():route.abort());
try{
 await page.goto(base+'/index.html',{waitUntil:'domcontentloaded'});
 await page.locator('#bottom button.tab[data-value="sights"]').click();
 await page.locator('.photo-pick .photo-error23').first().waitFor({timeout:15000});
 const card=page.locator('.photo-pick article').first();
 check('Missing photo displays explicit placeholder',await card.locator('.photo-error23').count()===1);
 const indicator=await card.locator('.photo-error23').innerText();
 check('Korean placeholder explains unavailable photo',indicator.includes('사진을 불러올 수 없습니다'),indicator);
 const p=await card.locator('img').first().evaluate(el=>({retry:el.dataset.retry23,failed:el.dataset.failed23}));
 check('Original-image fallback is attempted only once',p.failed==='yes',JSON.stringify(p));
 await card.locator('button.heart').click({timeout:5000});
 check('Saved heart remains clickable over missing photo',await card.locator('button.heart').getAttribute('aria-pressed')==='true');
 await card.locator('button.cardclick').click({timeout:5000});
 check('Sight detail remains clickable with missing photo',await page.locator('#layer [role="dialog"]').count()>0);
 await page.screenshot({path:'artifacts/phase16/fallback-korean.png',animations:'disabled'});
 await page.locator('#layer button[data-act="close-detail"]').first().click();
 await page.locator('#bottom button.tab[data-value="home"]').click();
 await page.locator('.vn-language-toggle').click();
 await page.locator('#bottom button.tab[data-value="sights"]').click();
 await page.locator('.photo-pick .photo-error23').first().waitFor({timeout:12000});
 const enText=await page.locator('.photo-pick .photo-error23').first().innerText();
 check('English fallback explains unavailable photo',enText.includes('Photo unavailable'),enText);
 await page.screenshot({path:'artifacts/phase16/fallback-english.png',animations:'disabled'});
}catch(e){issues.push('Flow: '+String(e.stack||e).slice(0,1200));}
await writeFile('artifacts/phase16/report.json',JSON.stringify({checks,issues,method:'Chromium browser with blocked external image endpoints to force real image error handlers'},null,2));
await browser.close();
console.log('Phase 16 fallback: '+checks.filter(x=>x.ok).length+'/'+checks.length+' passed; '+issues.length+' issues');
issues.forEach(x=>console.error('FAIL '+x));
if(issues.length)process.exitCode=1;
