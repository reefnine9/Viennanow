import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
const base=process.env.VIENNANOW_TEST_URL||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true});
const ctx=await browser.newContext({viewport:{width:390,height:780},reducedMotion:'reduce',locale:'ko-KR'});
const page=await ctx.newPage(),checks=[],issues=[];
const verify=(name,ok,detail='')=>{checks.push({name,ok:!!ok,detail});if(!ok)issues.push(name+': '+detail);};
const leaflet=readFileSync('node_modules/leaflet/dist/leaflet.js');
await mkdir('artifacts/phase13',{recursive:true});
page.on('pageerror',e=>issues.push('Runtime '+e.message));
await page.route('**/*',route=>{
 const u=route.request().url();
 if(u.includes('/leaflet@1.9.4/dist/leaflet.js'))return route.fulfill({status:200,contentType:'application/javascript',body:leaflet});
 if(u.startsWith(base+'/'))return route.continue();
 return route.abort();
});
try{
 await page.goto(base+'/index.html',{waitUntil:'domcontentloaded'});
 await page.locator('#bottom button.tab[data-value="food"]').click();
 const heart=page.locator('.vn64-food-grid .vn64-food-heart').first();
 await heart.waitFor({timeout:15000});
 const id=await heart.getAttribute('data-id');
 verify('Restaurant initial unsaved',await heart.getAttribute('aria-pressed')==='false',id);
 await heart.click({timeout:8000});
 verify('Restaurant favorite toggles',await page.locator('.vn64-food-grid .vn64-food-heart[data-id="'+id+'"]').getAttribute('aria-pressed')==='true',id);
 verify('Restaurant favorite persisted',await page.evaluate(id=>JSON.parse(localStorage.getItem('viennanow_p9')||'{}').savedRestaurants?.includes(id),id),id);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#bottom button.tab[data-value="food"]').click();
 await page.locator('.vn64-food-grid .vn64-food-heart[data-id="'+id+'"]').waitFor({timeout:12000});
 verify('Restaurant survives reload',await page.locator('.vn64-food-grid .vn64-food-heart[data-id="'+id+'"]').getAttribute('aria-pressed')==='true',id);
 await page.locator('#bottom button.tab[data-value="itinerary"]').click();
 await page.locator('[data-act="section-plan"][data-value="mine"]').click();
 verify('Restaurant in saved Plan',await page.locator('.vn59-saved-card button[data-act="vn58-food-heart"][data-id="'+id+'"]').count()===1,id);
 await page.locator('.vn59-saved-card button[data-act="vn58-food-heart"][data-id="'+id+'"]').click();
 verify('Restaurant removed in Plan',await page.locator('.vn59-saved-card button[data-act="vn58-food-heart"][data-id="'+id+'"]').count()===0,id);
 verify('Restaurant removal persists',await page.evaluate(id=>!(JSON.parse(localStorage.getItem('viennanow_p9')||'{}').savedRestaurants||[]).includes(id),id),id);
 await page.locator('#bottom button.tab[data-value="food"]').click();
 await page.locator('.vn64-food-grid .vn64-food-open[data-id="'+id+'"]').click();
 verify('Restaurant detail opens',await page.locator('#layer .vn64-food-drawer[role="dialog"]').count()===1);
 await page.locator('#layer button[data-act="vn64-food-close"]').first().click();
 verify('Restaurant detail closes',await page.locator('#layer [role="dialog"]').count()===0);
 await page.locator('#bottom button.tab[data-value="map"]').click();
 await page.locator('#map .leaflet-marker-icon').first().waitFor({timeout:12000});
 const pins=await page.locator('#map .leaflet-marker-icon').count();
 verify('Real Leaflet markers rendered',pins>0,'count='+pins);
 // The centre of Vienna has densely overlapping pins at zoom 13; zoom on the target before a true pointer click.
 await page.evaluate(()=>{const p=CATALOG48[0];map.setView([p.lat,p.lon],18);});
 await page.waitForTimeout(350);
 await page.locator('#map .leaflet-marker-icon[title="슈테판 대성당"]').click({timeout:8000});
 await page.locator('.leaflet-popup-content .vn34-sight-card').waitFor({timeout:8000});
 verify('Real marker click displays photo popup',await page.locator('.leaflet-popup-content .vn34-sight-card').count()>0);
 await page.screenshot({path:'artifacts/phase13/sight-map-popup.png',animations:'disabled'});
 await page.locator('.leaflet-popup-content .vn34-sight-card').first().click({timeout:8000});
 verify('Popup opens corresponding detail',await page.locator('#layer [role="dialog"]').count()>0);
 await page.screenshot({path:'artifacts/phase13/map-to-detail.png',animations:'disabled'});
}catch(e){issues.push('Flow interrupted: '+String(e.stack||e).slice(0,1700));}
await writeFile('artifacts/phase13/report.json',JSON.stringify({checks,issues,method:'Real Leaflet JS via local dependency; external tiles/images disabled; clicks through Chromium'},null,2));
await browser.close();
console.log('Phase 13: '+checks.filter(x=>x.ok).length+'/'+checks.length+' checks passed; '+issues.length+' issues');
issues.forEach(x=>console.error('FAIL '+x));
if(issues.length)process.exitCode=1;
